// ─── Compile patterns ─────────────────────────────────────────────────────────
const COMPILED_PATTERNS = RAW_PATTERNS.map(([pat, flags]) => {
  try {
    return new RegExp(pat, flags || 'i');
  } catch (e) {
    // Skip invalid patterns silently
    return null;
  }
}).filter(Boolean);

/**
 * Extract the first OTP (4–8 digits) from a message string.
 * @param {string} text
 * @returns {string|null}
 */
function extractOtpFromMessage(text) {
  if (!text || typeof text !== 'string') return null;

  for (const re of COMPILED_PATTERNS) {
    const m = re.exec(text);
    if (m) {
      // Handle split patterns (groups 1 + 2)
      if (m[2] !== undefined) {
        const combined = m[1] + m[2];
        if (combined.length >= 4 && combined.length <= 8) return combined;
      }
      if (m[1] !== undefined) {
        const code = m[1].replace(/\D/g, '');
        if (code.length >= 4 && code.length <= 8) return code;
      }
    }
  }
  return null;
}

